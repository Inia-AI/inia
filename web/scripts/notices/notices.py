"""Lists every package that this repository's lock files and package restore resolve, with its
licence, and checks each licence against scripts/notices/policy.json.

The list is the generated part of THIRD-PARTY-NOTICES.md, between its two marker lines. `write`
rewrites that part. `check` builds it again and fails when the file holds a different list, or when
a package's licence is outside the policy. In a tree with NuGet packages, run `dotnet restore` on
the whole solution first.

Each source in the policy names a type and a path. Where each type finds its packages and their
licences:
- nuget: the packages of each framework in every project.assets.json that the path matches, and
  each package's .nuspec in the restore's package folder. A framework restored for one runtime,
  such as an app's own platform, is left out, so the list is the same on every machine.
- npm: a package-lock.json of version 2 or 3, which carries each licence.
- bun: a bun.lock, and the npm registry, because the lock carries no licence.
- uv: a uv.lock, and PyPI, because the lock carries no licence.

The policy holds three lists:
- allowed: the licences any package may have.
- declared: what a package's metadata means when it is not a licence expression, such as a
  licence file or a link. A person writes the entry after reading the package's terms. It matches
  the metadata exactly. For a licence file the metadata holds the file's hash, so the package
  fails the check again when the file changes.
- exceptions: packages under terms outside the allowed list, admitted at one version each. An
  exception names the licence, the reason and a file with the full terms, which goes into the
  notices. A new version fails the check until a person reviews it and moves the exception.

A package that comes from git or a URL instead of a registry fails the check: the notices cannot
read its licence.

Usage: python3 scripts/notices/notices.py check|write [--root <repository>]. It needs Python 3.11
or later.
"""

import argparse
import difflib
import hashlib
import http.client
import json
import re
import sys
import time
import tomllib
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET
from collections.abc import Callable
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from pathlib import Path

NOTICES_FILE = "THIRD-PARTY-NOTICES.md"
POLICY_FILE = "scripts/notices/policy.json"
START = "<!-- generated by scripts/notices/notices.py: start -->"
END = "<!-- generated by scripts/notices/notices.py: end -->"
WRITE_COMMAND = "python3 scripts/notices/notices.py write"
NPM_REGISTRY = "https://registry.npmjs.org"
PYPI = "https://pypi.org/pypi"
FETCH_ATTEMPTS = 3
FETCH_TIMEOUT_SECONDS = 10
FETCH_WORKERS = 16
TOO_MANY_REQUESTS = 429
METADATA_TEXT_LIMIT = 120
NO_METADATA = "no licence in its metadata"
LOCAL_VERSION = re.compile(r"^(workspace|link|file):")
LOCAL_UV_SOURCES = {"virtual", "editable", "directory", "path"}
EXPRESSION_CHARACTERS = re.compile(r"[\sA-Za-z0-9.+:()-]*")
TOKEN = re.compile(r"[()]|[A-Za-z0-9.+:-]+")
OPERATORS = {"AND", "OR", "WITH"}

Fetch = Callable[[str], dict]


class NoticesError(Exception):
    pass


@dataclass(frozen=True)
class Package:
    source: str
    name: str
    version: str
    metadata: str

    @property
    def key(self) -> str:
        return f"{self.source}:{self.name}"


def fetch_json(url: str) -> dict:
    request = urllib.request.Request(url, headers={"Accept": "application/json", "User-Agent": "notices.py"})
    for attempt in range(1, FETCH_ATTEMPTS + 1):
        try:
            with urllib.request.urlopen(request, timeout=FETCH_TIMEOUT_SECONDS) as response:
                return json.load(response)
        except urllib.error.HTTPError as error:
            if (error.code < 500 and error.code != TOO_MANY_REQUESTS) or attempt == FETCH_ATTEMPTS:
                raise NoticesError(f"cannot read {url}: {error}") from error
        except (OSError, http.client.HTTPException, ValueError) as error:
            if attempt == FETCH_ATTEMPTS:
                raise NoticesError(f"cannot read {url}: {error}") from error
        time.sleep(attempt)
    raise AssertionError("unreachable")


def fetch_all(wanted: list[tuple[str, str]], read: Callable[[str, str], Package]) -> list[Package]:
    pool = ThreadPoolExecutor(max_workers=FETCH_WORKERS)
    try:
        return list(pool.map(lambda pair: read(*pair), wanted))
    finally:
        pool.shutdown(cancel_futures=True)


def nuget_packages(root: Path, source: dict, _fetch: Fetch) -> list[Package]:
    assets_files = sorted(root.glob(source["path"]))
    if not assets_files:
        raise NoticesError(f"no {source['path']} found; run dotnet restore on the whole solution first")
    candidates: dict[str, list[Path]] = {}
    for assets_file in assets_files:
        assets = json.loads(assets_file.read_text(encoding="utf-8"))
        for framework, resolved in assets["targets"].items():
            if "/" in framework:
                continue
            for name_and_version, entry in resolved.items():
                if entry.get("type") == "package":
                    path = assets["libraries"][name_and_version]["path"]
                    candidates[name_and_version] = [Path(folder) / path for folder in assets["packageFolders"]]
    packages = []
    for name_and_version, folders in candidates.items():
        name, version = name_and_version.split("/", 1)
        nuspecs = sorted(nuspec for folder in folders for nuspec in folder.glob("*.nuspec"))
        if not nuspecs:
            raise NoticesError(f"{name} {version} has no .nuspec in the restore's package folder; run dotnet restore again")
        packages.append(Package("nuget", name, version, nuspec_metadata(nuspecs[0])))
    return packages


def nuspec_metadata(nuspec: Path) -> str:
    metadata = next(element for element in ET.parse(nuspec).getroot() if element.tag.endswith("metadata"))
    fields = {element.tag.split("}")[-1]: element for element in metadata}
    licence = fields.get("license")
    text = (licence.text or "").strip() if licence is not None else ""
    if licence is not None and licence.get("type") == "expression":
        return text
    if licence is not None and licence.get("type") == "file":
        file = text.replace("\\", "/")
        return f"file {file} sha256:{hashlib.sha256((nuspec.parent / file).read_bytes()).hexdigest()[:16]}"
    if fields.get("licenseUrl") is not None:
        return f"url {(fields['licenseUrl'].text or '').strip()}"
    return NO_METADATA


def npm_packages(root: Path, source: dict, _fetch: Fetch) -> list[Package]:
    lock = json.loads((root / source["path"]).read_text(encoding="utf-8"))
    packages = {}
    for path, entry in lock.get("packages", {}).items():
        if path == "" or entry.get("link") or "version" not in entry:
            continue
        name = entry.get("name") or path.rsplit("node_modules/", 1)[-1]
        packages[(name, entry["version"])] = Package("npm", name, entry["version"], npm_metadata(entry))
    return list(packages.values())


def npm_metadata(manifest: dict) -> str:
    licence = manifest.get("license")
    if isinstance(licence, str):
        return licence
    if isinstance(licence, dict):
        return str(licence.get("type"))
    if isinstance(manifest.get("licenses"), list):
        return "licenses " + ", ".join(str(item.get("type") if isinstance(item, dict) else item) for item in manifest["licenses"])
    return NO_METADATA


def bun_packages(root: Path, source: dict, fetch: Fetch) -> list[Package]:
    text = (root / source["path"]).read_text(encoding="utf-8")
    lock = json.loads(re.sub(r",(\s*[}\]])", r"\1", text))
    wanted = set()
    for entry in lock.get("packages", {}).values():
        name, _, version = entry[0].rpartition("@")
        if not name or LOCAL_VERSION.match(version):
            continue
        if ":" in version or "/" in version:
            raise NoticesError(f"{source['path']}: {name} {version} comes from outside the registry, so its licence cannot be read")
        wanted.add((name, version))
    return fetch_all(sorted(wanted), lambda name, version: Package("bun", name, version, npm_metadata(fetch(f"{NPM_REGISTRY}/{name}/{version}"))))


def uv_packages(root: Path, source: dict, fetch: Fetch) -> list[Package]:
    lock = tomllib.loads((root / source["path"]).read_text(encoding="utf-8"))
    wanted = set()
    for entry in lock.get("package", []):
        kinds = set(entry.get("source", {}))
        if kinds & LOCAL_UV_SOURCES:
            continue
        if "registry" not in kinds:
            raise NoticesError(f"{source['path']}: {entry['name']} {entry['version']} comes from outside the registry, so its licence cannot be read")
        wanted.add((entry["name"], entry["version"]))
    return fetch_all(sorted(wanted), lambda name, version: Package("uv", name, version, pypi_metadata(fetch(f"{PYPI}/{name}/{version}/json")["info"])))


def pypi_metadata(info: dict) -> str:
    if info.get("license_expression"):
        return info["license_expression"]
    text = " ".join((info.get("license") or "").split())[:METADATA_TEXT_LIMIT]
    if parse_expression(text) is not None:
        return text
    classifiers = [classifier for classifier in info.get("classifiers") or [] if classifier.startswith("License ::")]
    parts = ([f"license: {text}"] if text else []) + ([f"classifiers: {'; '.join(classifiers)}"] if classifiers else [])
    return "; ".join(parts) or NO_METADATA


SOURCES: dict[str, tuple[str, Callable[[Path, dict, Fetch], list[Package]]]] = {
    "nuget": ("NuGet", nuget_packages),
    "npm": ("npm", npm_packages),
    "bun": ("bun", bun_packages),
    "uv": ("uv", uv_packages),
}


def parse_expression(text: str) -> object | None:
    if not EXPRESSION_CHARACTERS.fullmatch(text):
        return None
    tokens = TOKEN.findall(text)

    def chain(index: int, word: str, operand: Callable[[int], tuple[object, int] | None]) -> tuple[object, int] | None:
        parsed = operand(index)
        while parsed is not None and parsed[1] < len(tokens) and tokens[parsed[1]].upper() == word:
            right = operand(parsed[1] + 1)
            parsed = None if right is None else ((word, parsed[0], right[0]), right[1])
        return parsed

    def either(index: int) -> tuple[object, int] | None:
        return chain(index, "OR", lambda start: chain(start, "AND", single))

    def single(index: int) -> tuple[object, int] | None:
        if index >= len(tokens) or tokens[index] == ")" or tokens[index].upper() in OPERATORS:
            return None
        if tokens[index] == "(":
            inner = either(index + 1)
            if inner is None or inner[1] >= len(tokens) or tokens[inner[1]] != ")":
                return None
            return inner[0], inner[1] + 1
        following = tokens[index + 1 : index + 3]
        if len(following) == 2 and following[0].upper() == "WITH" and following[1] not in ("(", ")") and following[1].upper() not in OPERATORS:
            return f"{tokens[index]} WITH {following[1]}", index + 3
        return tokens[index], index + 1

    parsed = either(0)
    return parsed[0] if parsed is not None and parsed[1] == len(tokens) else None


def satisfies(expression: object, allowed: set[str]) -> bool:
    if isinstance(expression, str):
        return expression in allowed
    operator, left, right = expression  # type: ignore[misc]
    if operator == "OR":
        return satisfies(left, allowed) or satisfies(right, allowed)
    return satisfies(left, allowed) and satisfies(right, allowed)


def judge(packages: list[Package], policy: dict) -> tuple[dict[Package, str | None], list[str]]:
    declared = {(entry["package"], entry["metadata"]): entry["licence"] for entry in policy.get("declared", [])}
    exceptions = {(key, entry["version"]): entry["licence"] for entry in policy.get("exceptions", []) for key in entry["packages"]}
    allowed = set(policy["allowed"])
    licences: dict[Package, str | None] = {}
    problems = []
    for package in packages:
        excepted = exceptions.get((package.key, package.version))
        licence = excepted or declared.get((package.key, package.metadata))
        expression = parse_expression(licence or package.metadata)
        licences[package] = licence or (package.metadata if expression is not None else None)
        if excepted is not None:
            continue
        if licences[package] is None:
            problems.append(
                f"{package.key} {package.version}: its metadata says '{package.metadata}', which is not a licence expression. "
                f"Read its terms and add a declared entry to {POLICY_FILE}."
            )
        elif expression is None or not satisfies(expression, allowed):
            problems.append(
                f"{package.key} {package.version}: its licence {licences[package]} is not on the allowed list in {POLICY_FILE}. "
                f"Remove the package, or add an exception for this version with the reason and the terms. "
                f"When the metadata names the licence loosely, such as BSD for BSD-3-Clause, add a declared entry instead."
            )
    for key, metadata in sorted(set(declared) - {(package.key, package.metadata) for package in packages}):
        problems.append(f"{POLICY_FILE}: the declared entry for {key} ('{metadata}') matches no package; remove it.")
    for key, version in sorted(set(exceptions) - {(package.key, package.version) for package in packages}):
        problems.append(f"{POLICY_FILE}: the exception for {key} {version} matches no package; remove it.")
    return licences, problems


def render(sources: list[tuple[dict, list[Package]]], licences: dict[Package, str | None], policy: dict, root: Path) -> str:
    lines = [
        START,
        "## Packages",
        "",
        "Every package that the lock files and the package restore resolve, build and test tools included, with",
        f"the licence its metadata or a reviewed entry in `{POLICY_FILE}` gives. A package appears once per",
        f"licence, without its version, so an update under the same licence leaves the list as it is. `{WRITE_COMMAND}`",
        "writes this list, and CI fails when it is out of date or a licence is outside the policy.",
    ]
    for source, packages in sources:
        lines += ["", f"### {SOURCES[source['type']][0]} packages (`{source['path']}`)", "", "| Package | Licence |", "| --- | --- |"]
        rows = sorted({(package.name, licences[package] or "unknown") for package in packages}, key=lambda row: (row[0].lower(), row[1]))
        lines += [f"| {name} | {licence} |" for name, licence in rows]
    terms: dict[str, list[str]] = {}
    for entry in policy.get("exceptions", []):
        terms.setdefault(entry["terms"], []).extend(f"{key.split(':', 1)[1]} {entry['version']}" for key in entry["packages"])
    if terms:
        lines += ["", "### Terms outside the allowed list", ""]
        lines += ["These packages are under terms that are not on the allowed list. Their terms follow in full."]
        for path, names in terms.items():
            text = (root / Path(POLICY_FILE).parent / path).read_text(encoding="utf-8").rstrip()
            lines += ["", f"#### {', '.join(sorted(names))}", "", "```text", text, "```"]
    lines.append(END)
    return "\n".join(lines)


def build(root: Path, fetch: Fetch = fetch_json) -> tuple[str, list[str]]:
    policy = json.loads((root / POLICY_FILE).read_text(encoding="utf-8"))
    sources = []
    for source in policy["sources"]:
        if source["type"] not in SOURCES:
            raise NoticesError(f"{POLICY_FILE}: unknown source type {source['type']}")
        sources.append((source, SOURCES[source["type"]][1](root, source, fetch)))
    licences, problems = judge([package for _, packages in sources for package in packages], policy)
    return render(sources, licences, policy, root), problems


def split_notices(text: str) -> tuple[str, str, str]:
    if text.count(START) != 1 or text.count(END) != 1 or text.index(START) > text.index(END):
        raise NoticesError(f"{NOTICES_FILE} must hold the line {START} once, and then the line {END} once")
    head, rest = text.split(START, 1)
    body, tail = rest.split(END, 1)
    return head, START + body + END, tail


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="List the third-party packages and check their licences.")
    parser.add_argument("command", choices=["check", "write"])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2], help="the repository (default: this script's)")
    args = parser.parse_args(argv)
    notices_path = args.root / NOTICES_FILE
    try:
        head, current, tail = split_notices(notices_path.read_text(encoding="utf-8"))
        generated, problems = build(args.root)
    except (NoticesError, OSError, KeyError, ValueError) as error:
        print(f"notices failed: {error}", file=sys.stderr)
        return 2
    if args.command == "write":
        notices_path.write_text(head + generated + tail, encoding="utf-8")
    elif generated != current:
        diff = difflib.unified_diff(current.splitlines(), generated.splitlines(), NOTICES_FILE, "resolved packages", lineterm="", n=0)
        problems.insert(0, f"{NOTICES_FILE} lists other packages than the lock files and the restore resolve. Run {WRITE_COMMAND}.\n" + "\n".join(diff))
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        return 1
    print(f"{NOTICES_FILE} is up to date, and every licence is within {POLICY_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

<script lang="ts" setup>
import { computed, PropType, ref, watch } from 'vue'
import { useForm, Field as FormField } from 'vee-validate'
import { useI18n } from 'vue-i18n'

import type { CounterpartyDetails } from '@/api/counterparties/schema'
import { generateSlug, sanitizeId } from '@/composables/useReferenceId'
import { blankToNull, buildCounterpartyFormSchema } from './schema'
import {
  FormItem,
  FormLabel,
  FormControl,
  FormMessage,
} from '@/components/ui/form'
import { Button } from '@/components/ui/button'
import { Input } from '@/components/ui/input'
import { Textarea } from '@/components/ui/textarea'
import { MultiSelect, KeyValueEditor } from '@/components/molecules'
import { OptionType } from '@/types'

type CounterpartyFormValues = {
  id: string
  name: string
  nameVariants: string
  email: string
  website: string
  lastFinancialAnalysisResult: string
  counterpartyTypeIds: string[]
}

type InitialValues = Partial<CounterpartyDetails> & { id?: string }

const { t: $t } = useI18n()

const $emits = defineEmits(['submit', 'cancel'])

const props = defineProps({
  counterpartyTypes: {
    type: Array as PropType<OptionType[]>,
    required: true,
  },
  initialValues: {
    type: Object as PropType<InitialValues | null>,
    required: false,
    default: null,
  },
})

const isEditMode = computed(() => !!props.initialValues?.id)
const isIdManuallyEdited = ref(false)

const idFieldLabel = computed(() =>
  $t(isEditMode.value
    ? 'shared.components.counterpartySelect.referenceId.labelEdit'
    : 'shared.components.counterpartySelect.referenceId.label'),
)

const isAutoGeneratedId = computed(
  () => !isEditMode.value && !isIdManuallyEdited.value && (formData.value.id?.length ?? 0) > 0,
)

const defaultValues: CounterpartyFormValues = {
  id: '',
  name: '',
  nameVariants: '',
  email: '',
  website: '',
  lastFinancialAnalysisResult: '',
  counterpartyTypeIds: [],
}

const fromInitialValues = (
  raw: InitialValues | null | undefined,
): CounterpartyFormValues => ({
  id: raw?.id ?? '',
  name: raw?.name ?? '',
  nameVariants: raw?.nameVariants ?? '',
  email: raw?.email ?? '',
  website: raw?.website ?? '',
  lastFinancialAnalysisResult: raw?.lastFinancialAnalysisResult ?? '',
  counterpartyTypeIds: raw?.counterpartyTypeIds ?? [],
})

const formData = ref<CounterpartyFormValues>(
  props.initialValues ? fromInitialValues(props.initialValues) : { ...defaultValues },
)

const propertiesRecord = ref<Record<string, string>>(
  props.initialValues?.properties ?? {},
)

const schema = computed(() => buildCounterpartyFormSchema($t))

const form = useForm<CounterpartyFormValues>({
  validationSchema: schema,
  initialValues: formData.value,
})

const handleSubmit = form.handleSubmit(data => {
  $emits('submit', {
    ...data,
    email: blankToNull(data.email),
    website: blankToNull(data.website),
    properties: { ...propertiesRecord.value },
  })
})

watch(
  () => formData.value.name,
  newName => {
    if (!isEditMode.value && !isIdManuallyEdited.value) {
      const slug = generateSlug(newName)
      formData.value.id = slug
      form.setFieldValue('id', slug)
    }
  },
)

function handleIdInput(value: string) {
  isIdManuallyEdited.value = true
  const sanitized = sanitizeId(value)
  formData.value.id = sanitized
  form.setFieldValue('id', sanitized)
}

watch(
  () => props.initialValues,
  newValues => {
    if (newValues) {
      Object.assign(formData.value, fromInitialValues(newValues))
      isIdManuallyEdited.value = !!newValues.id
    } else {
      Object.assign(formData.value, { ...defaultValues })
      isIdManuallyEdited.value = false
    }
    propertiesRecord.value = newValues?.properties ?? {}
    form.resetForm({ values: formData.value })
  },
  { immediate: true },
)
</script>

<template>
  <form @submit="handleSubmit" class="flex min-h-0 flex-1 flex-col">
    <div class="flex min-h-0 flex-1 flex-col gap-2 overflow-y-auto pr-1">
    <FormField v-slot="{ componentField }" name="name">
      <FormItem>
        <FormLabel>Name</FormLabel>
        <FormControl>
          <Input
            v-bind="componentField"
            v-model="formData.name"
            placeholder="Enter name"
          />
        </FormControl>
        <FormMessage />
      </FormItem>
    </FormField>

    <FormField name="id">
      <FormItem>
        <FormLabel>{{ idFieldLabel }}</FormLabel>
        <FormControl>
          <Input
            :model-value="formData.id"
            :disabled="isEditMode"
            :class="{ 'text-muted-foreground italic': isAutoGeneratedId }"
            :placeholder="$t('shared.components.counterpartySelect.referenceId.placeholder')"
            @update:model-value="handleIdInput($event as string)"
          />
        </FormControl>
        <p v-if="!isEditMode" class="text-xs text-muted-foreground mt-1">
          {{ $t('shared.components.counterpartySelect.referenceId.hint') }}
        </p>
        <FormMessage />
      </FormItem>
    </FormField>

    <FormField v-slot="{ componentField }" name="nameVariants">
      <FormItem>
        <FormLabel>Name Variants</FormLabel>
        <FormControl>
          <Input
            v-bind="componentField"
            v-model="formData.nameVariants"
            placeholder="Enter name variants, separated by |"
          />
        </FormControl>
        <FormMessage />
      </FormItem>
    </FormField>

    <FormField v-slot="{ componentField }" name="email">
      <FormItem>
        <FormLabel>Email</FormLabel>
        <FormControl>
          <Input
            v-bind="componentField"
            v-model="formData.email"
            placeholder="Enter email"
          />
        </FormControl>
        <FormMessage />
      </FormItem>
    </FormField>

    <FormField v-slot="{ componentField }" name="website">
      <FormItem>
        <FormLabel>Website</FormLabel>
        <FormControl>
          <Input
            v-bind="componentField"
            v-model="formData.website"
            placeholder="Enter website URL"
          />
        </FormControl>
        <FormMessage />
      </FormItem>
    </FormField>

    <FormField v-slot="{ componentField }" name="counterpartyTypeIds">
      <FormItem>
        <FormLabel>Type</FormLabel>
        <FormControl>
          <MultiSelect
            v-bind="componentField"
            v-model="formData.counterpartyTypeIds"
            :options="counterpartyTypes"
          />
        </FormControl>
        <FormMessage />
      </FormItem>
    </FormField>

    <FormField v-slot="{ componentField }" name="lastFinancialAnalysisResult">
      <FormItem>
        <FormLabel>Last Financial Analysis Result</FormLabel>
        <FormControl>
          <Textarea
            v-bind="componentField"
            v-model="formData.lastFinancialAnalysisResult"
            placeholder="Enter analysis result"
          />
        </FormControl>
        <FormMessage />
      </FormItem>
    </FormField>

    <div class="mt-2 border-t pt-2">
      <p class="text-sm font-medium">
        {{ $t('page.counterpartyManagement.form.properties.heading') }}
      </p>
      <p class="text-xs text-muted-foreground">
        {{ $t('page.counterpartyManagement.form.properties.description') }}
      </p>
    </div>

    <KeyValueEditor
      v-model="propertiesRecord"
      name-prefix="property"
      :key-placeholder="$t('page.counterpartyManagement.form.properties.keyPlaceholder')"
      :value-placeholder="$t('page.counterpartyManagement.form.properties.valuePlaceholder')"
      :add-label="$t('page.counterpartyManagement.form.properties.addLabel')"
      :remove-label="$t('page.counterpartyManagement.form.properties.removeLabel')"
      :duplicate-key-message="$t('page.counterpartyManagement.form.properties.duplicateKey')"
    />
    </div>

    <div class="flex shrink-0 justify-end gap-4 border-t pt-4">
      <Button variant="outline" @click="$emit('cancel')">
        {{ $t('page.counterpartyManagement.form.cancelLabel') }}
      </Button>
      <Button type="submit" variant="soft">
        {{ $t('page.counterpartyManagement.form.submitLabel') }}
      </Button>
    </div>
  </form>
</template>

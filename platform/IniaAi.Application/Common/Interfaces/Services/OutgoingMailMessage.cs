namespace IniaAi.Application.Common.Interfaces.Services;

/// <summary>
/// One HTML mail with the headers a notice needs. <see cref="IOutgoingMail"/> strips CR and LF from
/// the subject, the reply-to address and every header value before it sends, so text that reaches a
/// header cannot add a header of its own.
/// </summary>
/// <param name="To">The recipient's address.</param>
/// <param name="Subject">The subject line.</param>
/// <param name="HtmlBody">The HTML body.</param>
public sealed record OutgoingMailMessage(string To, string Subject, string HtmlBody)
{
    /// <summary>The header that marks a mail as sent by a machine (RFC 3834), so auto-replies skip it.</summary>
    public const string AUTO_SUBMITTED_HEADER = "Auto-Submitted";

    /// <summary>The <see cref="AUTO_SUBMITTED_HEADER"/> value of a notice the platform sends on its own.</summary>
    public const string AUTO_GENERATED = "auto-generated";

    /// <summary>The headers of a notice the platform sends on its own.</summary>
    public static readonly IReadOnlyDictionary<string, string> AutoGeneratedHeaders =
        new Dictionary<string, string> { [AUTO_SUBMITTED_HEADER] = AUTO_GENERATED }.AsReadOnly();

    /// <summary>Where a reply to the mail goes, when not to the sender.</summary>
    public string? ReplyTo { get; init; }

    /// <summary>Extra headers, by name.</summary>
    public IReadOnlyDictionary<string, string> Headers { get; init; } = new Dictionary<string, string>();

    /// <summary>The same mail with CR and LF taken out of every value that becomes a header.</summary>
    public OutgoingMailMessage WithoutLineBreaksInHeaders()
    {
        return this with
        {
            To = StripLineBreaks(To),
            Subject = StripLineBreaks(Subject),
            ReplyTo = ReplyTo is null ? null : StripLineBreaks(ReplyTo),
            Headers = Headers.ToDictionary(header => StripLineBreaks(header.Key), header => StripLineBreaks(header.Value)),
        };
    }

    private static string StripLineBreaks(string value)
    {
        return value.Replace("\r", string.Empty, StringComparison.Ordinal).Replace("\n", string.Empty, StringComparison.Ordinal);
    }
}

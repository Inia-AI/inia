using IniaAi.AiConnection.Abstractions;
using IniaAi.AiConnection.Anthropic.ApiModel.Enums;
using IniaAi.AiConnection.Common;
using IniaAi.AiConnection.Common.ChatConnector;
using IniaAi.AiConnection.Enums;
using IniaAi.Common.Extensions;
using IniaAi.Common.Serialization;
using IniaAi.Configuration.Enums.Anthropic;
using Newtonsoft.Json;
using Newtonsoft.Json.Converters;

namespace IniaAi.AiConnection.Anthropic.ApiModel;

/// <summary>
/// Represents the response body of the Anthropic API.
/// </summary>
[JsonObject(MemberSerialization.OptIn)]
internal class ResponseBody : JsonSerializable<ResponseBody>
{
    public const string CACHE_CREATION_INPUT_TOKENS_KEY = "CacheCreationInputTokens";
    public const string CACHE_READ_INPUT_TOKENS_KEY = "CacheReadInputTokens";
    public const string STOP_REASON_KEY = "StopReason";

    /// <summary>
    /// Content generated by the model. This is an array of content blocks,
    /// each of which has a type that determines its shape. Currently,
    /// the only type in responses is "text".
    /// </summary>
    [JsonProperty("content")]
    public List<ContentResponse> Content { get; set; } = [];

    /// <summary>
    /// Unique object identifier. The format and length of IDs may
    /// change over time.
    /// </summary>
    [JsonProperty("id")]
    public string Id { get; set; } = "";

    /// <summary>
    /// The model that handled the request. Null when the response names a model
    /// this build does not know.
    /// </summary>
    [JsonProperty("model", NullValueHandling = NullValueHandling.Ignore)]
    [JsonConverter(typeof(TolerantStringEnumConverter))]
    public AiModel? Model { get; set; }

    /// <summary>
    /// Conversational role of the generated message. This will always be
    /// <seealso cref="MessageSenderRole.Assistant"/> for messages generated by
    /// the model.
    /// </summary>
    [JsonProperty("role")]
    [JsonConverter(typeof(StringEnumConverter))]
    public MessageSenderRole Role { get; set; } = MessageSenderRole.Assistant;

    /// <summary>
    /// The reason that the generation stopped.
    /// This may be one the following values:
    /// <list type="bullet">
    /// <item>
    /// "end_turn": the model reached a natural stopping point
    /// </item>
    /// <item>
    /// "max_tokens": we exceeded the requested max_tokens or the model's maximum
    /// </item>
    /// <item>
    /// "stop_sequence": one of your provided custom stop_sequences was generated
    /// </item>
    /// <item>
    /// "refusal": the model refused to generate content, typically for safety reasons
    /// </item>
    /// <item>
    /// "model_context_window_exceeded": generation stopped because the model's context window was reached
    /// </item>
    /// </list>
    /// Note that these values are different than those in /v1/complete, where
    /// end_turn and stop_sequence were not differentiated. In non-streaming
    /// mode this value is always non-null. In streaming mode, it is null in
    /// the message_start event and non-null otherwise.
    /// </summary>
    [JsonProperty("stop_reason")]
    [JsonConverter(typeof(TolerantStringEnumConverter))]
    public StopReasonType? StopReason { get; set; }

    /// <summary>
    /// The refusal category and explanation when <see cref="StopReason"/> is a refusal; null otherwise.
    /// </summary>
    [JsonProperty("stop_details", NullValueHandling = NullValueHandling.Ignore)]
    public StopDetails? StopDetails { get; set; }

    /// <summary>
    /// Which custom stop sequence was generated, if any. This value will be a
    /// non-null string if one of your custom stop sequences was generated.
    /// </summary>
    [JsonProperty("stop_sequence")]
    public string? StopSequence { get; set; }

    /// <summary>
    /// Object type. For Messages, this is always "message".
    /// </summary>
    [JsonProperty("type")]
    [JsonConverter(typeof(StringEnumConverter))]
    public ResponseType? Type { get; set; }

    /// <summary>
    /// Billing and rate-limit usage.
    /// <para>Anthropic's API bills and rate-limits by token counts, as tokens
    /// represent the underlying cost to our systems.
    /// </para>
    /// <para>Under the hood, the API transforms requests into a format suitable
    /// for the model. The model's output then goes through a parsing stage
    /// before becoming an API response. As a result, the token counts in
    /// usage will not match one-to-one with the exact visible content of an
    /// API request or response.
    /// </para>
    /// <para>For example, output_tokens will be non-zero,
    /// even for an empty string response from Claude.
    /// </para>
    /// </summary>
    [JsonProperty("usage", NullValueHandling = NullValueHandling.Ignore)]
    public Usage? BasicUsage { get; set; } = null;

    /// <summary>
    /// AWS Usage
    /// </summary>
    [JsonProperty("amazon-bedrock-invocationMetrics", NullValueHandling = NullValueHandling.Ignore)]
    public AWSUsage? AWSUsage { get; set; } = null;

    /// <summary>
    /// Usage
    /// </summary>
    public IUsage? Usage => (IUsage?)BasicUsage ?? AWSUsage;

    public ResponseContentSequence FormatResponseContent()
    {
        ResponseContentSequence responses = [];

        AppendMessagesToResponse(responses);

        responses.InputTokens = Usage?.InputTokens
            ?? 0;
        responses.OutputTokens = Usage?.OutputTokens
            ?? 0;

        if (Usage?.CacheCreationInputTokens > 0)
        {
            responses.Metadata[CACHE_CREATION_INPUT_TOKENS_KEY] = Usage.CacheCreationInputTokens;
        }

        if (Usage?.CacheReadInputTokens > 0)
        {
            responses.Metadata[CACHE_READ_INPUT_TOKENS_KEY] = Usage.CacheReadInputTokens;
        }

        if (StopReason is not null)
        {
            responses.Metadata[STOP_REASON_KEY] = StopReason.ToString()
                ?? StopReasonType.EndTurn.ToString();
        }

        // Add model ID to metadata for token usage tracking
        string? responseModelId = Model?.GetEnumMember();
        if (!string.IsNullOrEmpty(responseModelId))
        {
            responses.Metadata[ModelIdNormalizer.MODEL_METADATA_KEY] = responseModelId;
        }

        // A refusal can arrive after partial output; the partial is not an answer.
        if (StopReason is StopReasonType.Refusal)
        {
            responses.MarkRefused(new ModelRefusal(
                ModelRefusal.NormalizeCategory(StopDetails?.Category),
                StopDetails?.Explanation,
                string.IsNullOrWhiteSpace(Id) ? null : Id,
                responseModelId));
        }

        return responses;
    }

    private void AppendMessagesToResponse(ResponseContentSequence responses)
    {
        List<ResponseCommonContent>? thinkingFallbacks = null;

        for (int i = 0; i < Content.Count; i++)
        {
            ContentResponse message = Content[i];

            if (message is null)
            {
                continue;
            }

            var response = message.ToResponseCommonContent();

            if (response is not null)
            {
                responses.Add(response);
                continue;
            }

            // Collect thinking content as fallback in case no text/image content exists
            ResponseCommonContent? fallback = message.ToResponseCommonContentIncludeThinking();
            if (fallback is not null)
            {
                thinkingFallbacks ??= [];
                thinkingFallbacks.Add(fallback);
            }
        }

        // If no content was added, use thinking content as fallback
        if (!responses.Any() && thinkingFallbacks is not null)
        {
            foreach (ResponseCommonContent fallback in thinkingFallbacks)
            {
                responses.Add(fallback);
            }

            responses.IsThinkingOnly = true;
        }
    }
}
